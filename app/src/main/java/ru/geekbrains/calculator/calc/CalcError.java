package ru.geekbrains.calculator.calc;

/**
 * Машинно-читаемые коды ошибок калькулятора.
 * Текст сообщений живёт в ресурсах ({@code R.string.error_*}),
 * поэтому вычислительная часть не зависит от Android.
 */
public enum CalcError {

    /** Выражение пустое — вычислять нечего. */
    EMPTY,

    /** Некорректная запись выражения (например, два оператора подряд или лишняя скобка). */
    SYNTAX,

    /** Деление на ноль. */
    DIVIDE_BY_ZERO,

    /** Корень из отрицательного числа. */
    INVALID_SQRT,

    /** Переполнение: результат вышел за разумные пределы. */
    OVERFLOW
}
